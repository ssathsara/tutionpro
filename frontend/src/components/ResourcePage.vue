<script setup lang="ts">
import { computed, onMounted, reactive, ref, watch } from 'vue'
import { api, errorMessage } from '../api/client'
import type { ColumnDef, FieldDef } from '../types'
import { toast } from '../stores/toast'
import { clearOptionsCache } from '../composables/useOptions'
import FormField from './FormField.vue'
import Modal from './Modal.vue'
import Pagination from './Pagination.vue'
import Icon from './Icon.vue'
import FilterOptions from './FilterOptions.vue'

/**
 * Generic list + create/edit/delete page driven by column and field definitions.
 */
const props = withDefaults(defineProps<{
  title: string
  subtitle?: string
  endpoint: string
  columns: ColumnDef[]
  fields?: FieldDef[]
  filters?: FieldDef[]
  canCreate?: boolean
  canEdit?: boolean
  canDelete?: boolean
  searchable?: boolean
  createLabel?: string
  entityName?: string
  defaults?: Record<string, any>
  /** Map a row to the form model when editing. */
  toForm?: (row: any) => Record<string, any>
  /** Map the form model to the API payload. */
  toPayload?: (form: Record<string, any>, editing: boolean) => Record<string, any>
  /** Send updates as POST multipart (for file uploads). */
  multipart?: boolean
  rowLink?: (row: any) => string | null
  query?: Record<string, any>
  hideHeader?: boolean
  paginated?: boolean
}>(), {
  fields: () => [], filters: () => [], canCreate: false, canEdit: false, canDelete: false, searchable: true,
  entityName: 'record', defaults: () => ({}), paginated: true,
})

const emit = defineEmits<{ saved: [row: any]; loaded: [rows: any[]] }>()

const rows = ref<any[]>([])
const loading = ref(false)
const page = ref(1)
const lastPage = ref(1)
const total = ref(0)
const search = ref('')
const filterValues = reactive<Record<string, any>>({})
const showForm = ref(false)
const editing = ref<any | null>(null)
const form = ref<Record<string, any>>({})
const errors = ref<Record<string, string>>({})
const saving = ref(false)
const formError = ref('')
/** Login details generated by the server; shown once so the admin can hand them over. */
const credentials = ref<{ role: string; name: string; login: string; password: string }[]>([])
const copied = ref(false)
function credentialText() {
  return credentials.value.map((c) => `${c.name} (${c.role})\nLogin: ${c.login}\nPassword: ${c.password}`).join('\n\n')
    + `\n\nSign in at ${location.origin}/login and change the password from "My profile".`
}
async function copyCredentials() {
  try { await navigator.clipboard.writeText(credentialText()); copied.value = true; setTimeout(() => (copied.value = false), 2000) }
  catch { toast('Copy failed. Please select and copy the details manually.', 'error') }
}

async function load() {
  loading.value = true
  try {
    const params: Record<string, any> = { page: page.value, ...props.query }
    if (search.value) params.search = search.value
    for (const [k, v] of Object.entries(filterValues)) if (v !== null && v !== '' && v !== undefined) params[k] = v
    const { data } = await api.get(props.endpoint, { params })
    if (Array.isArray(data)) {
      rows.value = data; total.value = data.length; lastPage.value = 1
    } else {
      rows.value = data.data; total.value = data.total; lastPage.value = data.last_page; page.value = data.current_page
    }
    emit('loaded', rows.value)
  } catch (e) {
    toast(errorMessage(e), 'error')
  } finally {
    loading.value = false
  }
}

let timer: ReturnType<typeof setTimeout> | undefined
watch(search, () => { clearTimeout(timer); timer = setTimeout(() => { page.value = 1; load() }, 300) })
watch(filterValues, () => { page.value = 1; load() })
watch(() => props.query, () => { page.value = 1; load() }, { deep: true })
onMounted(load)

function cell(row: any, col: ColumnDef) {
  const v = col.key.split('.').reduce((o, k) => (o == null ? o : o[k]), row)
  if (col.format) return col.format(v, row)
  if (v === null || v === undefined || v === '') return '—'
  if (typeof v === 'boolean') return v ? 'Yes' : 'No'
  return String(v)
}

function toLocalInput(v: any) {
  if (!v) return v
  const d = new Date(v)
  if (isNaN(d.getTime())) return v
  const p = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}T${p(d.getHours())}:${p(d.getMinutes())}`
}

function openCreate() {
  editing.value = null
  const f: Record<string, any> = {}
  for (const fd of props.fields) f[fd.key] = fd.type === 'checkbox' ? false : fd.type === 'multiselect' ? [] : null
  form.value = { ...f, ...props.defaults }
  errors.value = {}; formError.value = ''
  showForm.value = true
}

function openEdit(row: any) {
  editing.value = row
  const base = props.toForm ? props.toForm(row) : { ...row }
  for (const fd of props.fields) {
    if (fd.type === 'datetime-local') base[fd.key] = toLocalInput(base[fd.key])
    if (fd.type === 'date' && typeof base[fd.key] === 'string') base[fd.key] = base[fd.key].slice(0, 10)
    if (fd.type === 'time' && typeof base[fd.key] === 'string') base[fd.key] = base[fd.key].slice(0, 5)
    if (fd.type === 'password' || fd.type === 'file') base[fd.key] = null
  }
  form.value = base
  errors.value = {}; formError.value = ''
  showForm.value = true
}

const visibleFields = computed(() => props.fields.filter((f) => !(f.createOnly && editing.value)))

async function save() {
  saving.value = true; errors.value = {}; formError.value = ''
  try {
    const raw: Record<string, any> = {}
    for (const f of props.fields) raw[f.key] = form.value[f.key]
    let payload: any = props.toPayload ? props.toPayload({ ...form.value, ...raw }, !!editing.value) : raw
    // Strip empty passwords so they are not changed on edit
    for (const f of props.fields) if (f.type === 'password' && !payload[f.key]) delete payload[f.key]

    let res
    if (props.multipart) {
      const fd = new FormData()
      const fileKeys = new Set(props.fields.filter((f) => f.type === 'file').map((f) => f.key))
      for (const [k, v] of Object.entries(payload)) {
        if (v === undefined) continue
        // Send cleared fields as '' (Laravel turns it into null) so edits can remove a value;
        // an empty file input means "keep the current file".
        if (v === null) { if (!fileKeys.has(k)) fd.append(k, ''); continue }
        if (typeof v === 'boolean') fd.append(k, v ? '1' : '0')
        else fd.append(k, v as any)
      }
      res = editing.value
        ? await api.post(`${props.endpoint}/${editing.value.id}`, fd)
        : await api.post(props.endpoint, fd)
    } else {
      res = editing.value
        ? await api.put(`${props.endpoint}/${editing.value.id}`, payload)
        : await api.post(props.endpoint, payload)
    }
    toast(res.data?.scheduled
      ? `${props.entityName[0].toUpperCase() + props.entityName.slice(1)} scheduled. It will be sent at the chosen time.`
      : `${props.entityName[0].toUpperCase() + props.entityName.slice(1)} ${editing.value ? 'updated' : 'created'}`)
    if (res.data?.credentials?.length) credentials.value = res.data.credentials
    showForm.value = false
    clearOptionsCache()
    emit('saved', res.data)
    load()
  } catch (e: any) {
    const errs = e?.response?.data?.errors
    if (errs) for (const [k, v] of Object.entries(errs)) errors.value[k.split('.')[0]] = (v as string[])[0]
    formError.value = errorMessage(e)
  } finally {
    saving.value = false
  }
}

async function remove(row: any) {
  if (!confirm(`Delete this ${props.entityName}? This cannot be undone.`)) return
  try {
    await api.delete(`${props.endpoint}/${row.id}`)
    toast(`${props.entityName[0].toUpperCase() + props.entityName.slice(1)} deleted`)
    clearOptionsCache()
    load()
  } catch (e) {
    toast(errorMessage(e), 'error')
  }
}

defineExpose({ reload: load, openCreate, openEdit, rows })
</script>

<template>
  <div class="page">
    <div v-if="!hideHeader" class="page-header">
      <div>
        <h1>{{ title }}</h1>
        <p v-if="subtitle" class="sub">{{ subtitle }}</p>
      </div>
      <div class="row">
        <slot name="header-actions" />
        <button v-if="canCreate && fields.length" class="btn btn-primary" @click="openCreate">
          <Icon name="plus" :size="16" /> {{ createLabel ?? `New ${entityName}` }}
        </button>
      </div>
    </div>

    <div class="card">
      <div v-if="searchable || filters.length || $slots.toolbar" class="card-header toolbar">
        <div v-if="searchable" class="search">
          <Icon name="search" :size="16" />
          <input v-model="search" class="input" type="search" :placeholder="`Search ${title.toLowerCase()}…`" aria-label="Search" />
        </div>
        <div v-for="f in filters" :key="f.key" class="filter">
          <select v-if="f.type === 'select'" v-model="filterValues[f.key]" class="input" :aria-label="f.label">
            <option :value="undefined">{{ f.label }}: All</option>
            <FilterOptions :field="f" />
          </select>
          <input v-else v-model="filterValues[f.key]" class="input" :type="f.type ?? 'text'" :aria-label="f.label" :title="f.label" />
        </div>
        <slot name="toolbar" />
      </div>

      <div v-if="loading && !rows.length" class="loading-block"><span class="spinner" /> Loading…</div>
      <div v-else-if="!rows.length" class="empty">
        <slot name="empty">No {{ entityName }}s found.</slot>
      </div>
      <div v-else class="table-wrap">
        <table class="table">
          <thead>
            <tr>
              <th v-for="c in columns" :key="c.key">{{ c.label }}</th>
              <th v-if="canEdit || canDelete || $slots.actions" class="actions"><span class="sr-only">Actions</span></th>
            </tr>
          </thead>
          <tbody>
            <tr v-for="row in rows" :key="row.id">
              <td v-for="(c, ci) in columns" :key="c.key">
                <slot :name="`cell-${c.key}`" :row="row" :value="cell(row, c)">
                  <RouterLink v-if="ci === 0 && rowLink && rowLink(row)" :to="rowLink(row)!" class="strong">{{ cell(row, c) }}</RouterLink>
                  <template v-else>{{ cell(row, c) }}</template>
                </slot>
              </td>
              <td v-if="canEdit || canDelete || $slots.actions" class="actions">
                <slot name="actions" :row="row" :reload="load" />
                <button v-if="canEdit" class="btn btn-sm btn-ghost" title="Edit" @click="openEdit(row)"><Icon name="edit" :size="15" /></button>
                <button v-if="canDelete" class="btn btn-sm btn-ghost btn-danger" title="Delete" @click="remove(row)"><Icon name="trash" :size="15" /></button>
              </td>
            </tr>
          </tbody>
        </table>
      </div>
      <Pagination v-if="paginated" :page="page" :last-page="lastPage" :total="total" @change="(p) => { page = p; load() }" />
    </div>

    <Modal v-if="showForm" :title="`${editing ? 'Edit' : 'New'} ${entityName}`" @close="showForm = false">
      <form id="resource-form" class="form-grid" @submit.prevent="save">
        <div v-if="formError && !Object.keys(errors).length" class="alert alert-danger full">{{ formError }}</div>
        <FormField v-for="f in visibleFields" :key="f.key" v-model="form[f.key]" :field="f" :error="errors[f.key]" />
        <slot name="form-extra" :form="form" :editing="editing" />
      </form>
      <template #footer>
        <button class="btn" type="button" @click="showForm = false">Cancel</button>
        <button class="btn btn-primary" type="submit" form="resource-form" :disabled="saving">
          <span v-if="saving" class="spinner" /> {{ editing ? 'Save changes' : 'Create' }}
        </button>
      </template>
    </Modal>

    <Modal v-if="credentials.length" title="Login details" width="520px" @close="credentials = []">
      <div class="stack">
        <div class="alert alert-warning">Give these details to the user now. For security, the password is shown <strong>only once</strong> and cannot be viewed again (you can set a new one by editing the account).</div>
        <div v-for="c in credentials" :key="c.login" class="card card-body cred">
          <div class="row"><strong>{{ c.name }}</strong><span class="badge">{{ c.role }}</span></div>
          <div class="small"><span class="muted">Login:</span> <code class="sel">{{ c.login }}</code></div>
          <div class="small"><span class="muted">Password:</span> <code class="sel">{{ c.password }}</code></div>
        </div>
      </div>
      <template #footer>
        <button class="btn" @click="copyCredentials">{{ copied ? 'Copied ✓' : 'Copy all' }}</button>
        <button class="btn btn-primary" @click="credentials = []">Done</button>
      </template>
    </Modal>
  </div>
</template>


